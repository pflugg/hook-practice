export function def(id: string): CardDef {
  const card = CARDS[id];
  if (!card) throw new Error(`Unknown card ${id}`);
  return card;
}

export function villainCardIds(): string[] {
  return Object.values(CARDS)
    .filter((c) => c.deck === "villain")
    .flatMap((c) => Array.from({ length: c.copies }, () => c.id));
}

export function fateCardIds(): string[] {
  return Object.values(CARDS)
    .filter((c) => c.deck === "fate")
    .flatMap((c) => Array.from({ length: c.copies }, () => c.id));
}
